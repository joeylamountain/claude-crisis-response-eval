"""Build analysis/agreement.xlsx: a hand-checkable version of agreement.py.

Every statistic is a live Excel formula over the raw paired scores, so anyone can
recompute it (or change a score and watch kappa update).

  python analysis/build_agreement_xlsx.py            (needs: pip install openpyxl)

Layout
  README      how the sheet works, the formulas, sources
  D1 ... D6   column A = rater A (author), column B = rater B, one row per transcript
              (all 70, by random ID; NA rows stay visible and are excluded by formula),
              C = weighted disagreement (A-B)^2 / (K-1)^2, then Do, the 3x3 expected
              grid, De, weighted kappa, percent agreement, unweighted kappa
  Summary     one row per dimension, linked to the D sheets, next to agreement.py's
              values for comparison
"""

import csv
import os

from openpyxl import Workbook
from openpyxl.comments import Comment
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIMS = ["D1", "D2", "D3", "D4", "D5", "D6"]
LEVELS = [0, 1, 2]
FONT = "Arial"
BLUE = Font(name=FONT, color="0000FF")          # inputs (raw scores)
BLACK = Font(name=FONT)
BOLD = Font(name=FONT, bold=True)
GREEN = Font(name=FONT, color="008000")         # links to other sheets
HEAD_FILL = PatternFill("solid", fgColor="E7EEF7")
KEY_FILL = PatternFill("solid", fgColor="FFF2CC")
THIN = Border(bottom=Side(style="thin", color="999999"))


def load(path):
    with open(os.path.join(ROOT, path), newline="", encoding="utf-8-sig") as f:
        return {r["rid"]: r for r in csv.DictReader(f)}


def as_cell(v):
    v = (v or "").strip()
    return int(v) if v in ("0", "1", "2") else "NA"


def main():
    a = load("ratings/scores_rater_a.csv")   # published, transcript-free copies
    b = load("ratings/scores_rater_b.csv")
    py = {}
    py_path = os.path.join(ROOT, "analysis", "agreement.csv")
    if os.path.exists(py_path):
        with open(py_path, newline="", encoding="utf-8") as f:
            py = {r["dim"]: r for r in csv.DictReader(f)}
    rids = sorted(a)
    n_rows = len(rids)
    first, last = 2, 1 + n_rows

    wb = Workbook()
    ws = wb.active
    ws.title = "README"
    lines = [
        ("Inter-rater agreement: quadratic-weighted kappa, computed by formula", BOLD),
        ("", None),
        ("Source data: ratings/scores_rater_a.csv (rater A = author) and ratings/scores_rater_b.csv (rater B), main set, rubric v1.", BLACK),
        ("Each D sheet: column A = rater A's score, column B = rater B's score (blue = raw input). Scale 0-2, so K = 3 levels.", BLACK),
        ("NA = dimension not applicable to that transcript (pre-registered). NA rows stay visible and are excluded by the formulas, not deleted.", BLACK),
        ("", None),
        ("Formulas (black cells):", BOLD),
        ("C  weighted disagreement per item  = (A - B)^2 / (K-1)^2   (divisor = 4 for a 0-2 scale; it cancels in the kappa ratio)", BLACK),
        ("Do observed disagreement           = AVERAGE of column C over paired items", BLACK),
        ("pA(k), pB(k)                      = share of each rater's paired scores at level k", BLACK),
        ("De expected disagreement           = sum over i, j of pA(i) * pB(j) * (i - j)^2 / (K-1)^2   (the 3x3 grid)", BLACK),
        ("Weighted kappa                     = 1 - Do / De   ('undefined' when De = 0, i.e. both raters gave one identical score to every item)", BLACK),
        ("Percent agreement                  = share of paired items with A = B", BLACK),
        ("Unweighted kappa                   = (po - pe) / (1 - pe), with pe = sum over k of pA(k) * pB(k)", BLACK),
        ("", None),
        ("To recompute: change any blue score; every statistic updates. The Summary sheet compares these values with analysis/agreement.py.", BLACK),
        ("Bootstrap confidence intervals are computed only in agreement.py (resampling is not done in the sheet).", BLACK),
        ("Generated by analysis/build_agreement_xlsx.py.", BLACK),
    ]
    for i, (text, font) in enumerate(lines, 1):
        c = ws.cell(row=i, column=1, value=text)
        c.font = font or BLACK
    ws.column_dimensions["A"].width = 130

    summary_refs = {}
    for d in DIMS:
        s = wb.create_sheet(d)
        heads = ["Rater A", "Rater B", "(A-B)^2/(K-1)^2", "rid", "A = B (paired)"]
        for col, h in enumerate(heads, 1):
            c = s.cell(row=1, column=col, value=h)
            c.font, c.fill, c.border = BOLD, HEAD_FILL, THIN
        rng = lambda col: f"${col}${first}:${col}${last}"
        for r, rid in enumerate(rids, first):
            s.cell(row=r, column=1, value=as_cell(a[rid][d])).font = BLUE
            s.cell(row=r, column=2, value=as_cell(b[rid][d])).font = BLUE
            s.cell(row=r, column=3,
                   value=f'=IF(AND(ISNUMBER(A{r}),ISNUMBER(B{r})),(A{r}-B{r})^2/$H$3,"")').font = BLACK
            s.cell(row=r, column=4, value=rid).font = BLACK
            s.cell(row=r, column=5, value=f'=IF(ISNUMBER(C{r}),IF(A{r}=B{r},1,0),"")').font = BLACK

        # Parameters and results block (columns G-K)
        def put(row, label, formula, key=False, comment=None, fmt=None):
            s.cell(row=row, column=7, value=label).font = BOLD if key else BLACK
            c = s.cell(row=row, column=8, value=formula)
            c.font = BOLD if key else BLACK
            if key:
                c.fill = KEY_FILL
            if fmt:
                c.number_format = fmt
            if comment:
                c.comment = Comment(comment, "build_agreement_xlsx.py")
            return f"'{d}'!$H${row}" if " " in d else f"{d}!$H${row}"

        put(1, "Dimension", d, key=True)
        s.cell(row=2, column=7, value="K (levels)").font = BLACK
        s.cell(row=2, column=8, value=3).font = BLUE
        s.cell(row=2, column=8).comment = Comment("Rubric scale 0, 1, 2 (rubric/rubric.md).", "build")
        put(3, "(K-1)^2 divisor", "=(H2-1)^2")
        ref_n = put(4, "n paired items", f"=COUNT({rng('C')})", fmt="0")
        ref_do = put(5, "Do = observed disagreement", f"=IF(H4=0,\"\",AVERAGE({rng('C')}))", fmt="0.0000")

        # pA / pB table
        s.cell(row=7, column=7, value="level k").font = BOLD
        s.cell(row=7, column=8, value="pA(k)").font = BOLD
        s.cell(row=7, column=9, value="pB(k)").font = BOLD
        for i, k in enumerate(LEVELS):
            r = 8 + i
            s.cell(row=r, column=7, value=k).font = BLUE
            s.cell(row=r, column=8,
                   value=f"=IF($H$4=0,0,SUMPRODUCT(({rng('A')}=G{r})*ISNUMBER({rng('C')}))/$H$4)").number_format = "0.0000"
            s.cell(row=r, column=9,
                   value=f"=IF($H$4=0,0,SUMPRODUCT(({rng('B')}=G{r})*ISNUMBER({rng('C')}))/$H$4)").number_format = "0.0000"

        # 3x3 expected-disagreement grid: rows i (rater A level), cols j (rater B level)
        s.cell(row=12, column=7, value="Expected grid: pA(i)*pB(j)*(i-j)^2/(K-1)^2").font = BOLD
        s.cell(row=13, column=7, value="i \\ j").font = BOLD
        for jx, j in enumerate(LEVELS):
            s.cell(row=13, column=8 + jx, value=j).font = BOLD
        for ix, i in enumerate(LEVELS):
            r = 14 + ix
            s.cell(row=r, column=7, value=i).font = BOLD
            for jx, j in enumerate(LEVELS):
                col = 8 + jx
                colL = "HIJ"[jx]
                s.cell(row=r, column=col,
                       value=f"=$H${8 + ix}*$I${8 + jx}*($G${r}-{colL}$13)^2/$H$3").number_format = "0.0000"

        ref_de = put(18, "De = expected disagreement", "=SUM(H14:J16)", fmt="0.0000")
        ref_kw = put(19, "Weighted kappa = 1 - Do/De",
                     '=IF(H4=0,"undefined",IF(H18=0,"undefined",1-H5/H18))', key=True, fmt="0.000",
                     comment="Undefined when De = 0: both raters gave one identical score to every paired item.")
        ref_po = put(20, "Percent agreement (po)", f"=IF(H4=0,\"\",AVERAGE({rng('E')}))", key=True, fmt="0.0%")
        ref_pe = put(21, "pe (unweighted chance)", "=SUMPRODUCT(H8:H10,I8:I10)", fmt="0.0000")
        ref_ku = put(22, "Unweighted kappa", '=IF(H4=0,"undefined",IF(H21=1,"undefined",(H20-H21)/(1-H21)))',
                     fmt="0.000")
        ref_dis = put(23, "Items with A <> B", f"=H4-SUM({rng('E')})", fmt="0")
        summary_refs[d] = dict(n=ref_n, po=ref_po, kw=ref_kw, ku=ref_ku, dis=ref_dis, do=ref_do, de=ref_de)

        for col, w in zip("ABCDEFGHIJK", [10, 10, 16, 10, 14, 3, 34, 12, 12, 12, 3]):
            s.column_dimensions[col].width = w
        s.freeze_panes = "A2"

    # Summary
    sm = wb.create_sheet("Summary", 1)
    heads = ["Dimension", "n", "Percent agreement", "Items A<>B", "Weighted kappa (quadratic)",
             "Unweighted kappa", "Do", "De",
             "agreement.py %agree", "agreement.py kappa_qw", "agreement.py kappa 95% CI", "agreement.py alpha_ord",
             "Sheet = Python?"]
    for col, h in enumerate(heads, 1):
        c = sm.cell(row=1, column=col, value=h)
        c.font, c.fill, c.border = BOLD, HEAD_FILL, THIN
        c.alignment = Alignment(wrap_text=True, vertical="top")
    for r, d in enumerate(DIMS, 2):
        refs = summary_refs[d]
        sm.cell(row=r, column=1, value=d).font = BOLD
        for col, key, fmt in [(2, "n", "0"), (3, "po", "0.0%"), (4, "dis", "0"), (5, "kw", "0.000"),
                              (6, "ku", "0.000"), (7, "do", "0.0000"), (8, "de", "0.0000")]:
            c = sm.cell(row=r, column=col, value=f"={refs[key]}")
            c.font, c.number_format = GREEN, fmt
        p = py.get(d)
        if p:
            def num(x):
                return float(x) if x not in ("", None) else "undefined"
            vals = [num(p["pct_agree"]), num(p["kappa_qw"]),
                    "undefined" if p["kappa_lo"] == "" else f"[{float(p['kappa_lo']):.2f}, {float(p['kappa_hi']):.2f}]",
                    num(p["alpha_ord"])]
            for col, v, fmt in zip((9, 10, 11, 12), vals, ("0.0%", "0.000", "@", "0.000")):
                c = sm.cell(row=r, column=col, value=v)
                c.font, c.number_format = BLUE, fmt
            sm.cell(row=r, column=9).comment = Comment("Copied from analysis/agreement.csv (agreement.py output).", "build")
            sm.cell(row=r, column=13, value=(
                f'=IF(AND(ISNUMBER(E{r}),ISNUMBER(J{r})),IF(AND(ABS(E{r}-J{r})<0.000001,ABS(C{r}-I{r})<0.000001),"match","DIFFERS"),'
                f'IF(AND(E{r}="undefined",J{r}="undefined"),"match","DIFFERS"))')).font = BLACK
    note_row = len(DIMS) + 3
    sm.cell(row=note_row, column=1, value=(
        "Green = linked from the D sheets (live formulas). Blue = values copied from analysis/agreement.csv for comparison. "
        "Kappa is unstable when nearly every score is the same level (ceiling effect); read percent agreement first.")).font = BLACK
    for col, w in zip("ABCDEFGHIJKLM", [11, 6, 12, 10, 14, 12, 9, 9, 13, 13, 16, 13, 12]):
        sm.column_dimensions[col].width = w
    sm.row_dimensions[1].height = 45

    out = os.path.join(ROOT, "analysis", "agreement.xlsx")
    wb.save(out)
    print("wrote", out)


if __name__ == "__main__":
    main()
